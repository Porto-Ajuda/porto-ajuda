function abrirModalODS(numero) {

    const dados =
        dadosODS[numero];

    if (!dados) {

        console.warn(
            `Não existem informações cadastradas para a ODS ${numero}.`
        );

        return;
    }


    // Imagem

    const imagem =
        modalODS.querySelector(
            ".modal-ods-img"
        );

    imagem.src =
        `../assets/ods${numero}.png`;

    imagem.alt =
        `ODS ${numero} - ${dados.titulo}`;


    // Número

    modalODS.querySelector(
        ".modal-ods-numero"
    ).textContent =
        `ODS ${numero}`;


    // Título

    modalODS.querySelector(
        ".modal-ods-titulo"
    ).textContent =
        dados.titulo;


    // Descrição

    modalODS.querySelector(
        ".modal-ods-descricao"
    ).textContent =
        dados.descricao;


    // O que busca

    modalODS.querySelector(
        ".modal-ods-busca"
    ).textContent =
        dados.busca;


    // Metas

    const listaMetas =
        modalODS.querySelector(
            ".modal-ods-metas"
        );

    listaMetas.innerHTML = "";


    dados.metas.forEach(meta => {

        const li =
            document.createElement("li");

        li.textContent = meta;

        listaMetas.appendChild(li);

    });


    // Contribuição das ONGs

    modalODS.querySelector(
        ".modal-ods-contribuicao"
    ).textContent =
        dados.contribuicao;


    // Abre

    modalODS.classList.add("aberto");

    document.body.style.overflow = "hidden";
}


// ========================================
// FECHAR MODAL
// ========================================

function fecharModalODS() {

    modalODS.classList.remove("aberto");

    document.body.style.overflow = "";
}


// Fechar pelo X

modalODS
    .querySelector(".fechar-modal-ods")
    .addEventListener(
        "click",
        fecharModalODS
    );


// Fechar clicando fora

modalODS.addEventListener(
    "click",
    evento => {

        if (
            evento.target === modalODS
        ) {

            fecharModalODS();

        }

    }
);


// Fechar com ESC

document.addEventListener(
    "keydown",
    evento => {

        if (
            evento.key === "Escape" &&
            modalODS.classList.contains("aberto")
        ) {

            fecharModalODS();

        }

    }
);

