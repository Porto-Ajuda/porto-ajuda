    // ========================================
    // LIMPAR TEXTO
    // ========================================

    function limparTexto(texto) {

        return texto
            .normalize("NFD")
            .replace(/[\u0300-\u036f]/g, "")
            .replace(/[^a-zA-Z0-9 ]/g, "")
            .toUpperCase();

    }


    // ========================================
    // CAMPO PIX
    // ========================================

    function campoPix(id, valor) {

        const tamanho =
            valor.length
                .toString()
                .padStart(2, "0");

        return id + tamanho + valor;

    }


    // ========================================
    // CRC16
    // ========================================

    function calcularCRC16(payload) {

        let crc = 0xFFFF;

        for (
            let i = 0;
            i < payload.length;
            i++
        ) {

            crc ^=
                payload.charCodeAt(i) << 8;

            for (
                let j = 0;
                j < 8;
                j++
            ) {

                if (
                    (crc & 0x8000) !== 0
                ) {

                    crc =
                        (crc << 1) ^ 0x1021;

                } else {

                    crc <<= 1;

                }

                crc &= 0xFFFF;

            }

        }

        return crc
            .toString(16)
            .toUpperCase()
            .padStart(4, "0");

    }

    // ========================================
    // GERAR PIX
    // ========================================

    function gerarPix(valor) {

        valor = Number(valor);

        if (
            !Number.isFinite(valor) ||
            valor <= 0
        ) {

            alert(
                "Digite um valor válido."
            );

            return null;

        }


        // Verificar PIX da ONG

        if (!ong.pix) {

            alert(
                "Esta ONG ainda não possui uma chave PIX cadastrada."
            );

            return null;

        }


        const chavePix =
            ong.pix.chave;

        const nomeRecebedor =
            ong.pix.nome;

        const cidadeRecebedor =
            ong.pix.cidade;


        const nome =
            limparTexto(nomeRecebedor)
                .substring(0, 25);

        const cidade =
            limparTexto(cidadeRecebedor)
                .substring(0, 15);


        // 00 - Payload Format Indicator

        const payloadFormat =
            campoPix("00", "01");


        // 26 - Merchant Account Information

        const gui =
            campoPix(
                "00",
                "BR.GOV.BCB.PIX"
            );

        const chave =
            campoPix(
                "01",
                chavePix
            );

        const merchantAccountInformation =
            campoPix(
                "26",
                gui + chave
            );


        // 52 - Merchant Category Code

        const merchantCategoryCode =
            campoPix(
                "52",
                "0000"
            );


        // 53 - Moeda

        const moeda =
            campoPix(
                "53",
                "986"
            );


        // 54 - Valor

        const valorFormatado =
            valor.toFixed(2);

        const valorPix =
            campoPix(
                "54",
                valorFormatado
            );


        // 58 - País

        const pais =
            campoPix(
                "58",
                "BR"
            );


        // 59 - Nome

        const nomePix =
            campoPix(
                "59",
                nome
            );


        // 60 - Cidade

        const cidadePix =
            campoPix(
                "60",
                cidade
            );


        // 62 - TXID

        const txid =
            campoPix(
                "05",
                "***"
            );

        const dadosAdicionais =
            campoPix(
                "62",
                txid
            );


        // Montar payload

        let payload =
            payloadFormat +
            merchantAccountInformation +
            merchantCategoryCode +
            moeda +
            valorPix +
            pais +
            nomePix +
            cidadePix +
            dadosAdicionais;


        // CRC

        payload += "6304";

        const crc =
            calcularCRC16(payload);

        payload += crc;


        return payload;

    }

    // ========================================
    // MOSTRAR PIX
    // ========================================

    function mostrarPix(valor) {

        const pix =
            gerarPix(valor);

        if (!pix) {
            return;
        }


        // Verificar biblioteca

        if (
            typeof QRCode === "undefined"
        ) {

            console.error(
                "QRCode não foi carregado."
            );

            alert(
                "A biblioteca do QR Code não foi carregada."
            );

            return;

        }


        // Limpar QR anterior

        qrcode.innerHTML = "";


        // Gerar QR

        new QRCode(qrcode, {

            text: pix,

            width: 275,

            height: 275,

            correctLevel:
                QRCode.CorrectLevel.M

        });


        // Mostrar valor

        valorExibido.textContent =
            Number(valor).toLocaleString(
                "pt-BR",
                {
                    style: "currency",
                    currency: "BRL"
                }
            );


        // Mostrar chave da ONG

        chavePixInput.value =
            ong.pix.chave;


        // Mostrar PIX Copia e Cola

        pixCopiaCola.value =
            pix;


        // Mostrar resultado

        resultadoPix.style.display =
            "block";


        // Limpar mensagem

        mensagemCopia.textContent = "";


        // Rolar até o resultado

        resultadoPix.scrollIntoView({
            behavior: "smooth",
            block: "center"
        });

    }

