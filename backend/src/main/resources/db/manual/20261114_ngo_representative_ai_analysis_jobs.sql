-- Durable, provider-neutral queue for advisory NGO representative-document analysis.
-- One-shot additive migration. Do not execute until the AI provider, retention policy,
-- schema review, and TEST integration have been approved. No provider calls occur here.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '2min';

DO $preflight$
BEGIN
    IF to_regclass('public.ngo_representative_verification_applications') IS NULL
       OR to_regclass('public.ngo_representative_verification_submissions') IS NULL
       OR to_regclass('public.ngo_representative_verification_evidence') IS NULL THEN
        RAISE EXCEPTION 'Preflight: representative verification M14 dependencies are absent.';
    END IF;
    IF NOT has_schema_privilege(current_user, 'public', 'CREATE')
       OR NOT has_table_privilege(current_user, 'public.ngo_representative_verification_applications', 'SELECT,REFERENCES')
       OR NOT has_table_privilege(current_user, 'public.ngo_representative_verification_submissions', 'SELECT,REFERENCES')
       OR NOT has_table_privilege(current_user, 'public.ngo_representative_verification_evidence', 'SELECT,REFERENCES') THEN
        RAISE EXCEPTION 'Preflight: migration role lacks required schema/table privileges.';
    END IF;
    IF to_regclass('public.ngo_representative_verification_ai_jobs') IS NOT NULL
       OR to_regclass('public.ngo_representative_verification_ai_job_events') IS NOT NULL THEN
        RAISE EXCEPTION 'Preflight: AI analysis job objects already exist; inspect before any repair.';
    END IF;
    IF to_regclass('public.uq_ngo_verification_submission_id_application') IS NOT NULL THEN
        RAISE EXCEPTION 'Preflight: the migration-owned submission/application index already exists.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
        WHERE n.nspname='public' AND p.proname IN (
            'guard_ngo_verification_ai_job',
            'guard_ngo_verification_ai_job_event'
        )
    ) THEN
        RAISE EXCEPTION 'Preflight: AI analysis guard functions already exist.';
    END IF;
END
$preflight$;

-- Supports a composite FK so a job cannot pair an application with another application's submission.
CREATE UNIQUE INDEX uq_ngo_verification_submission_id_application
    ON public.ngo_representative_verification_submissions(id, application_id);

CREATE TABLE public.ngo_representative_verification_ai_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    submission_id BIGINT NOT NULL,
    analysis_profile VARCHAR(40) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    attempts SMALLINT NOT NULL DEFAULT 0,
    maximum_attempts SMALLINT NOT NULL DEFAULT 3,
    available_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    lease_owner UUID NULL,
    lease_expires_at TIMESTAMPTZ NULL,
    provider VARCHAR(40) NULL,
    model VARCHAR(80) NULL,
    input_tokens INTEGER NULL,
    output_tokens INTEGER NULL,
    result_schema_version VARCHAR(40) NULL,
    result_summary JSONB NULL,
    result_sha256 CHAR(64) NULL,
    last_error_code VARCHAR(40) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    completed_at TIMESTAMPTZ NULL,
    CONSTRAINT uq_ngo_verification_ai_job_submission_profile UNIQUE (submission_id, analysis_profile),
    CONSTRAINT fk_ngo_verification_ai_job_submission_application FOREIGN KEY (submission_id, application_id)
        REFERENCES public.ngo_representative_verification_submissions(id, application_id) ON DELETE RESTRICT,
    CONSTRAINT ck_ngo_verification_ai_job_profile CHECK (analysis_profile='REPRESENTATION_V1'),
    CONSTRAINT ck_ngo_verification_ai_job_status CHECK
        (status IN ('QUEUED','PROCESSING','RETRY','COMPLETED','FAILED','SUPERSEDED')),
    CONSTRAINT ck_ngo_verification_ai_job_attempts CHECK
        (maximum_attempts BETWEEN 1 AND 3 AND attempts BETWEEN 0 AND maximum_attempts),
    CONSTRAINT ck_ngo_verification_ai_job_provider_fields CHECK
        ((provider IS NULL OR length(btrim(provider)) BETWEEN 1 AND 40)
         AND (model IS NULL OR length(btrim(model)) BETWEEN 1 AND 80)
         AND (input_tokens IS NULL OR input_tokens >= 0)
         AND (output_tokens IS NULL OR output_tokens >= 0)
         AND (result_schema_version IS NULL OR length(btrim(result_schema_version)) BETWEEN 1 AND 40)
         AND (result_sha256 IS NULL OR result_sha256 ~ '^[0-9a-f]{64}$')),
    CONSTRAINT ck_ngo_verification_ai_job_error_code CHECK
        (last_error_code IS NULL OR last_error_code IN (
            'PROVIDER_UNAVAILABLE','PROVIDER_TIMEOUT','PROVIDER_REJECTED','INVALID_RESULT',
            'EVIDENCE_UNAVAILABLE','EVIDENCE_LIMIT_EXCEEDED','WORKER_LEASE_EXPIRED','INTERNAL_RETRYABLE',
            'PROVIDER_QUOTA_EXHAUSTED','PROVIDER_REFUSAL','INCOMPLETE_RESPONSE','INVALID_DOCUMENT',
            'PROVIDER_CONFIGURATION_ERROR')),
    CONSTRAINT ck_ngo_verification_ai_job_lease_state CHECK
        ((status='PROCESSING' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL AND completed_at IS NULL)
         OR (status<>'PROCESSING' AND lease_owner IS NULL AND lease_expires_at IS NULL)),
    CONSTRAINT ck_ngo_verification_ai_job_result_state CHECK
        ((status='COMPLETED' AND provider IS NOT NULL AND model IS NOT NULL
          AND result_schema_version IS NOT NULL AND result_summary IS NOT NULL
          AND jsonb_typeof(result_summary)='object' AND result_sha256 IS NOT NULL AND completed_at IS NOT NULL)
         OR (status<>'COMPLETED' AND result_summary IS NULL AND result_sha256 IS NULL)),
    CONSTRAINT ck_ngo_verification_ai_job_final_state CHECK
        ((status IN ('COMPLETED','FAILED','SUPERSEDED') AND completed_at IS NOT NULL)
         OR (status NOT IN ('COMPLETED','FAILED','SUPERSEDED') AND completed_at IS NULL))
);
CREATE INDEX idx_ngo_verification_ai_job_queue
    ON public.ngo_representative_verification_ai_jobs(status, available_at, created_at, id)
    WHERE status IN ('QUEUED','RETRY');
CREATE INDEX idx_ngo_verification_ai_job_expired_lease
    ON public.ngo_representative_verification_ai_jobs(lease_expires_at, id)
    WHERE status='PROCESSING';
CREATE INDEX idx_ngo_verification_ai_job_application
    ON public.ngo_representative_verification_ai_jobs(application_id, created_at DESC, id DESC);

-- Audit metadata only: never store document bytes, extracted values, quotations, credentials,
-- or untrusted provider prose in this append-only event table.
CREATE TABLE public.ngo_representative_verification_ai_job_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    event_type VARCHAR(24) NOT NULL,
    attempt SMALLINT NOT NULL,
    provider VARCHAR(40) NULL,
    model VARCHAR(80) NULL,
    error_code VARCHAR(40) NULL,
    result_sha256 CHAR(64) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT fk_ngo_verification_ai_job_event_job FOREIGN KEY (job_id)
        REFERENCES public.ngo_representative_verification_ai_jobs(id) ON DELETE RESTRICT,
    CONSTRAINT ck_ngo_verification_ai_job_event_type CHECK
        (event_type IN ('QUEUED','CLAIMED','RETRY_SCHEDULED','COMPLETED','FAILED','SUPERSEDED')),
    CONSTRAINT ck_ngo_verification_ai_job_event_attempt CHECK (attempt BETWEEN 0 AND 3),
    CONSTRAINT ck_ngo_verification_ai_job_event_provider CHECK
        ((provider IS NULL OR length(btrim(provider)) BETWEEN 1 AND 40)
         AND (model IS NULL OR length(btrim(model)) BETWEEN 1 AND 80)
         AND (result_sha256 IS NULL OR result_sha256 ~ '^[0-9a-f]{64}$')),
    CONSTRAINT ck_ngo_verification_ai_job_event_error CHECK
        (error_code IS NULL OR error_code IN (
            'PROVIDER_UNAVAILABLE','PROVIDER_TIMEOUT','PROVIDER_REJECTED','INVALID_RESULT',
            'EVIDENCE_UNAVAILABLE','EVIDENCE_LIMIT_EXCEEDED','WORKER_LEASE_EXPIRED','INTERNAL_RETRYABLE',
            'PROVIDER_QUOTA_EXHAUSTED','PROVIDER_REFUSAL','INCOMPLETE_RESPONSE','INVALID_DOCUMENT',
            'PROVIDER_CONFIGURATION_ERROR'))
);
CREATE INDEX idx_ngo_verification_ai_job_events_job
    ON public.ngo_representative_verification_ai_job_events(job_id, created_at, id);

CREATE FUNCTION public.guard_ngo_verification_ai_job()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'AI analysis jobs are retained; use an approved retention procedure.';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.application_id IS DISTINCT FROM OLD.application_id
       OR NEW.submission_id IS DISTINCT FROM OLD.submission_id
       OR NEW.analysis_profile IS DISTINCT FROM OLD.analysis_profile
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.maximum_attempts IS DISTINCT FROM OLD.maximum_attempts THEN
        RAISE EXCEPTION 'AI job identity and retry policy are immutable.';
    END IF;
    IF NEW.attempts < OLD.attempts OR NEW.attempts > NEW.maximum_attempts THEN
        RAISE EXCEPTION 'AI job attempts cannot be reset or exceed the bound.';
    END IF;
    IF NOT (
        (OLD.status='QUEUED' AND NEW.status IN ('PROCESSING','SUPERSEDED'))
        OR (OLD.status='RETRY' AND NEW.status IN ('PROCESSING','FAILED','SUPERSEDED'))
        OR (OLD.status='PROCESSING' AND NEW.status IN ('RETRY','COMPLETED','FAILED','SUPERSEDED'))
    ) THEN
        RAISE EXCEPTION 'Invalid AI job state transition.';
    END IF;
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END
$$;

CREATE FUNCTION public.guard_ngo_verification_ai_job_event()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'AI analysis job event history is immutable.';
END
$$;

CREATE TRIGGER trg_ngo_verification_ai_job_guard
    BEFORE UPDATE OR DELETE ON public.ngo_representative_verification_ai_jobs
    FOR EACH ROW EXECUTE FUNCTION public.guard_ngo_verification_ai_job();
CREATE TRIGGER trg_ngo_verification_ai_job_no_truncate
    BEFORE TRUNCATE ON public.ngo_representative_verification_ai_jobs
    FOR EACH STATEMENT EXECUTE FUNCTION public.guard_ngo_verification_ai_job_event();
CREATE TRIGGER trg_ngo_verification_ai_job_events_immutable
    BEFORE UPDATE OR DELETE ON public.ngo_representative_verification_ai_job_events
    FOR EACH ROW EXECUTE FUNCTION public.guard_ngo_verification_ai_job_event();
CREATE TRIGGER trg_ngo_verification_ai_job_events_no_truncate
    BEFORE TRUNCATE ON public.ngo_representative_verification_ai_job_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.guard_ngo_verification_ai_job_event();

ALTER TABLE public.ngo_representative_verification_ai_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ngo_representative_verification_ai_job_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ngo_representative_verification_ai_jobs,
    public.ngo_representative_verification_ai_job_events FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.ngo_representative_verification_ai_jobs_id_seq,
    public.ngo_representative_verification_ai_job_events_id_seq FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public.guard_ngo_verification_ai_job() FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION public.guard_ngo_verification_ai_job_event() FROM PUBLIC, anon, authenticated, service_role;

DO $postflight$
BEGIN
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.ngo_representative_verification_ai_jobs'::regclass)
       OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.ngo_representative_verification_ai_job_events'::regclass) THEN
        RAISE EXCEPTION 'Postflight: RLS is not enabled on both AI job tables.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_index WHERE indexrelid='public.uq_ngo_verification_ai_job_submission_profile'::regclass
                   AND indisunique AND indisvalid) THEN
        RAISE EXCEPTION 'Postflight: duplicate-job unique index is missing or invalid.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_index WHERE indexrelid='public.uq_ngo_verification_submission_id_application'::regclass
                   AND indisunique AND indisvalid) THEN
        RAISE EXCEPTION 'Postflight: submission/application integrity index is missing or invalid.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_ngo_verification_ai_job_guard'
                   AND tgrelid='public.ngo_representative_verification_ai_jobs'::regclass AND tgenabled<>'D')
       OR NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_ngo_verification_ai_job_events_immutable'
                   AND tgrelid='public.ngo_representative_verification_ai_job_events'::regclass AND tgenabled<>'D') THEN
        RAISE EXCEPTION 'Postflight: state guard or immutable event trigger is missing.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgname='trg_ngo_verification_ai_job_guard'
           AND tgrelid='public.ngo_representative_verification_ai_jobs'::regclass
           AND tgfoid='public.guard_ngo_verification_ai_job()'::regprocedure AND tgenabled<>'D'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgname='trg_ngo_verification_ai_job_no_truncate'
           AND tgrelid='public.ngo_representative_verification_ai_jobs'::regclass
           AND tgfoid='public.guard_ngo_verification_ai_job_event()'::regprocedure AND tgenabled<>'D'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgname='trg_ngo_verification_ai_job_events_immutable'
           AND tgrelid='public.ngo_representative_verification_ai_job_events'::regclass
           AND tgfoid='public.guard_ngo_verification_ai_job_event()'::regprocedure AND tgenabled<>'D'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgname='trg_ngo_verification_ai_job_events_no_truncate'
           AND tgrelid='public.ngo_representative_verification_ai_job_events'::regclass
           AND tgfoid='public.guard_ngo_verification_ai_job_event()'::regprocedure AND tgenabled<>'D'
    ) THEN
        RAISE EXCEPTION 'Postflight: an AI job trigger is missing, disabled, or bound to the wrong guard function.';
    END IF;
    IF has_table_privilege('anon','public.ngo_representative_verification_ai_jobs','SELECT,INSERT,UPDATE,DELETE,TRUNCATE')
       OR has_table_privilege('authenticated','public.ngo_representative_verification_ai_jobs','SELECT,INSERT,UPDATE,DELETE,TRUNCATE')
       OR has_table_privilege('service_role','public.ngo_representative_verification_ai_jobs','SELECT,INSERT,UPDATE,DELETE,TRUNCATE') THEN
        RAISE EXCEPTION 'Postflight: a REST role has direct access to private AI job data.';
    END IF;
END
$postflight$;

COMMIT;
