-- Porto Ajuda support conversations with 30-day post-closure content retention.
-- Product retention rule, not a legal-compliance guarantee. One-shot additive migration.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '2min';

DO $preflight$
BEGIN
    IF to_regclass('public.usuarios') IS NULL OR to_regclass('public.admin_assignments') IS NULL THEN
        RAISE EXCEPTION 'Preflight: user and administrative assignment tables are required.';
    END IF;
    IF to_regclass('public.support_conversations') IS NOT NULL
       OR to_regclass('public.support_messages') IS NOT NULL
       OR to_regclass('public.support_conversation_events') IS NOT NULL
       OR to_regclass('public.support_retention_authorizations') IS NOT NULL THEN
        RAISE EXCEPTION 'Preflight: support assistant objects already exist; inspect before repair.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
         WHERE n.nspname='public' AND p.proname IN (
             'guard_support_conversation_identity','prevent_support_history_mutation',
             'purge_expired_support_conversation')) THEN
        RAISE EXCEPTION 'Preflight: support assistant guard functions already exist.';
    END IF;
END
$preflight$;

CREATE TABLE public.support_conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_user_id INTEGER NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
    state VARCHAR(24) NOT NULL DEFAULT 'AI_ACTIVE',
    assigned_staff_user_id INTEGER NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    state_changed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    closed_at TIMESTAMPTZ NULL,
    content_purged_at TIMESTAMPTZ NULL,
    last_message_at TIMESTAMPTZ NULL DEFAULT clock_timestamp(),
    user_last_read_at TIMESTAMPTZ NULL DEFAULT clock_timestamp(),
    staff_last_read_at TIMESTAMPTZ NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_support_conversation_state CHECK (state IN ('AI_ACTIVE','WAITING_HUMAN','HUMAN_ACTIVE','CLOSED')),
    CONSTRAINT ck_support_conversation_version CHECK (version >= 0),
    CONSTRAINT ck_support_conversation_assignment CHECK
        ((state='HUMAN_ACTIVE' AND assigned_staff_user_id IS NOT NULL)
         OR (state<>'HUMAN_ACTIVE' AND assigned_staff_user_id IS NULL)),
    CONSTRAINT ck_support_conversation_closed_at CHECK
        ((state='CLOSED' AND closed_at IS NOT NULL) OR (state<>'CLOSED' AND closed_at IS NULL)),
    CONSTRAINT ck_support_conversation_purged CHECK
        (content_purged_at IS NULL OR
         (state='CLOSED' AND owner_user_id IS NULL AND last_message_at IS NULL
          AND user_last_read_at IS NULL AND staff_last_read_at IS NULL))
);
CREATE INDEX idx_support_conversations_owner_updated
    ON public.support_conversations(owner_user_id, updated_at DESC, id DESC);
CREATE INDEX idx_support_conversations_queue
    ON public.support_conversations(state, created_at, id)
    WHERE state IN ('WAITING_HUMAN','HUMAN_ACTIVE');
CREATE INDEX idx_support_conversations_assignee
    ON public.support_conversations(assigned_staff_user_id, updated_at DESC)
    WHERE assigned_staff_user_id IS NOT NULL;
CREATE INDEX idx_support_conversations_retention
    ON public.support_conversations(closed_at, id)
    WHERE state='CLOSED' AND content_purged_at IS NULL;

CREATE TABLE public.support_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES public.support_conversations(id) ON DELETE RESTRICT,
    sender_type VARCHAR(12) NOT NULL,
    sender_user_id INTEGER NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
    public_sender_label VARCHAR(48) NOT NULL,
    body TEXT NOT NULL,
    idempotency_key VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_support_message_sender CHECK (sender_type IN ('USER','AI','STAFF','SYSTEM')),
    CONSTRAINT ck_support_message_body CHECK (length(btrim(body)) BETWEEN 1 AND 8000),
    CONSTRAINT ck_support_message_idempotency CHECK (length(btrim(idempotency_key)) BETWEEN 1 AND 80),
    CONSTRAINT ck_support_message_sender_identity CHECK
        ((sender_type IN ('USER','STAFF'))
         OR (sender_type IN ('AI','SYSTEM') AND sender_user_id IS NULL))
);
CREATE UNIQUE INDEX uq_support_message_idempotency
    ON public.support_messages(conversation_id, sender_type, COALESCE(sender_user_id, -1), idempotency_key);
CREATE INDEX idx_support_messages_conversation_time
    ON public.support_messages(conversation_id, created_at, id);

CREATE TABLE public.support_conversation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES public.support_conversations(id) ON DELETE RESTRICT,
    actor_type VARCHAR(12) NOT NULL,
    actor_user_id INTEGER NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
    event_type VARCHAR(24) NOT NULL,
    previous_assignee_user_id_snapshot INTEGER NULL,
    new_assignee_user_id_snapshot INTEGER NULL,
    from_state VARCHAR(24) NULL,
    to_state VARCHAR(24) NULL,
    reason VARCHAR(1000) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_support_event_actor CHECK (actor_type IN ('USER','STAFF','SYSTEM')),
    CONSTRAINT ck_support_event_type CHECK
        (event_type IN ('CREATED','STATE_CHANGED','CLAIMED','TRANSFERRED','MESSAGE_SENT','AI_SUPPRESSED')),
    CONSTRAINT ck_support_event_state CHECK
        ((from_state IS NULL OR from_state IN ('AI_ACTIVE','WAITING_HUMAN','HUMAN_ACTIVE','CLOSED'))
         AND (to_state IS NULL OR to_state IN ('AI_ACTIVE','WAITING_HUMAN','HUMAN_ACTIVE','CLOSED'))),
    CONSTRAINT ck_support_event_reason CHECK (reason IS NULL OR length(reason) <= 1000)
);
CREATE INDEX idx_support_events_conversation_time
    ON public.support_conversation_events(conversation_id, created_at, id);

-- A transaction-scoped authorization used only by the SECURITY DEFINER purge function.
-- No application role can create or inspect these permits directly.
CREATE TABLE public.support_retention_authorizations (
    transaction_id BIGINT NOT NULL,
    backend_pid INTEGER NOT NULL,
    conversation_id UUID NOT NULL,
    PRIMARY KEY (transaction_id, backend_pid, conversation_id)
);

CREATE FUNCTION public.guard_support_conversation_identity()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE retention_purge BOOLEAN;
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'Support conversation history cannot be deleted through the application.';
    END IF;
    SELECT EXISTS (SELECT 1 FROM public.support_retention_authorizations a
                    WHERE a.transaction_id=txid_current() AND a.backend_pid=pg_backend_pid()
                      AND a.conversation_id=OLD.id) INTO retention_purge;
    IF NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id
       AND NOT (NEW.owner_user_id IS NULL AND OLD.owner_user_id IS NOT NULL
                AND (retention_purge OR NOT EXISTS (SELECT 1 FROM public.usuarios WHERE id=OLD.owner_user_id))) THEN
        RAISE EXCEPTION 'Support conversation owner is immutable except account deletion anonymization.';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Support conversation identity is immutable.';
    END IF;
    IF NEW.content_purged_at IS DISTINCT FROM OLD.content_purged_at
       AND NOT (retention_purge AND OLD.content_purged_at IS NULL AND NEW.content_purged_at IS NOT NULL) THEN
        RAISE EXCEPTION 'Conversation content purge is restricted to the retention procedure.';
    END IF;
    IF NEW.closed_at IS DISTINCT FROM OLD.closed_at AND NOT retention_purge
       AND NOT ((NEW.state='CLOSED' AND OLD.state<>'CLOSED' AND NEW.closed_at IS NOT NULL)
                OR (OLD.state='CLOSED' AND NEW.state<>'CLOSED' AND NEW.closed_at IS NULL)) THEN
        RAISE EXCEPTION 'Closure time changes only when closing or reopening a conversation.';
    END IF;
    IF ((OLD.last_message_at IS NOT NULL AND NEW.last_message_at IS NULL)
        OR (OLD.user_last_read_at IS NOT NULL AND NEW.user_last_read_at IS NULL)
        OR (OLD.staff_last_read_at IS NOT NULL AND NEW.staff_last_read_at IS NULL))
       AND NOT retention_purge THEN
        RAISE EXCEPTION 'Conversation read metadata can be removed only by retention.';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_support_conversation_identity
    BEFORE UPDATE OR DELETE ON public.support_conversations
    FOR EACH ROW EXECUTE FUNCTION public.guard_support_conversation_identity();

CREATE FUNCTION public.prevent_support_history_mutation()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE retention_purge BOOLEAN;
BEGIN
    IF TG_OP='TRUNCATE' THEN RAISE EXCEPTION 'Support histories cannot be truncated.'; END IF;
    SELECT EXISTS (SELECT 1 FROM public.support_retention_authorizations a
                    WHERE a.transaction_id=txid_current() AND a.backend_pid=pg_backend_pid()
                      AND a.conversation_id=COALESCE(OLD.conversation_id,NEW.conversation_id)) INTO retention_purge;
    IF TG_OP='DELETE' AND TG_TABLE_NAME='support_messages' AND retention_purge THEN RETURN OLD; END IF;
    IF TG_OP='UPDATE' AND TG_TABLE_NAME='support_messages' THEN
        IF OLD.sender_user_id IS NOT NULL AND NEW.sender_user_id IS NULL
           AND NEW.id IS NOT DISTINCT FROM OLD.id AND NEW.conversation_id IS NOT DISTINCT FROM OLD.conversation_id
           AND NEW.sender_type IS NOT DISTINCT FROM OLD.sender_type
           AND NEW.public_sender_label IS NOT DISTINCT FROM OLD.public_sender_label
           AND NEW.body IS NOT DISTINCT FROM OLD.body AND NEW.idempotency_key IS NOT DISTINCT FROM OLD.idempotency_key
           AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at
           AND NOT EXISTS (SELECT 1 FROM public.usuarios WHERE id=OLD.sender_user_id) THEN RETURN NEW; END IF;
    ELSIF TG_OP='UPDATE' AND TG_TABLE_NAME='support_conversation_events' THEN
        IF OLD.actor_user_id IS NOT NULL AND NEW.actor_user_id IS NULL
           AND NEW.id IS NOT DISTINCT FROM OLD.id AND NEW.conversation_id IS NOT DISTINCT FROM OLD.conversation_id
           AND NEW.actor_type IS NOT DISTINCT FROM OLD.actor_type AND NEW.event_type IS NOT DISTINCT FROM OLD.event_type
           AND NEW.previous_assignee_user_id_snapshot IS NOT DISTINCT FROM OLD.previous_assignee_user_id_snapshot
           AND NEW.new_assignee_user_id_snapshot IS NOT DISTINCT FROM OLD.new_assignee_user_id_snapshot
           AND NEW.from_state IS NOT DISTINCT FROM OLD.from_state AND NEW.to_state IS NOT DISTINCT FROM OLD.to_state
           AND NEW.reason IS NOT DISTINCT FROM OLD.reason AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at
           AND NOT EXISTS (SELECT 1 FROM public.usuarios WHERE id=OLD.actor_user_id) THEN RETURN NEW; END IF;
        IF retention_purge AND NEW.id IS NOT DISTINCT FROM OLD.id
           AND NEW.conversation_id IS NOT DISTINCT FROM OLD.conversation_id
           AND NEW.actor_type IS NOT DISTINCT FROM OLD.actor_type AND NEW.event_type IS NOT DISTINCT FROM OLD.event_type
           AND NEW.from_state IS NOT DISTINCT FROM OLD.from_state AND NEW.to_state IS NOT DISTINCT FROM OLD.to_state
           AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at
           AND NEW.actor_user_id IS NULL AND NEW.previous_assignee_user_id_snapshot IS NULL
           AND NEW.new_assignee_user_id_snapshot IS NULL AND NEW.reason IS NULL THEN RETURN NEW; END IF;
    END IF;
    RAISE EXCEPTION 'Support messages and transition history are append-only.';
END;
$$;
CREATE TRIGGER trg_support_conversations_no_truncate
    BEFORE TRUNCATE ON public.support_conversations
    FOR EACH STATEMENT EXECUTE FUNCTION public.prevent_support_history_mutation();
CREATE TRIGGER trg_support_messages_append_only
    BEFORE UPDATE OR DELETE ON public.support_messages
    FOR EACH ROW EXECUTE FUNCTION public.prevent_support_history_mutation();
CREATE TRIGGER trg_support_messages_no_truncate
    BEFORE TRUNCATE ON public.support_messages
    FOR EACH STATEMENT EXECUTE FUNCTION public.prevent_support_history_mutation();
CREATE TRIGGER trg_support_events_append_only
    BEFORE UPDATE OR DELETE ON public.support_conversation_events
    FOR EACH ROW EXECUTE FUNCTION public.prevent_support_history_mutation();
CREATE TRIGGER trg_support_events_no_truncate
    BEFORE TRUNCATE ON public.support_conversation_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.prevent_support_history_mutation();

CREATE FUNCTION public.purge_expired_support_conversation(p_conversation_id UUID, p_as_of TIMESTAMPTZ)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE
    current_state VARCHAR(24);
    closed_time TIMESTAMPTZ;
    purged_time TIMESTAMPTZ;
BEGIN
    IF p_as_of IS NULL OR p_as_of > clock_timestamp() THEN RETURN FALSE; END IF;
    SELECT state,closed_at,content_purged_at INTO current_state,closed_time,purged_time
      FROM public.support_conversations WHERE id=p_conversation_id FOR UPDATE;
    IF NOT FOUND OR current_state <> 'CLOSED' OR closed_time IS NULL OR purged_time IS NOT NULL
       OR p_as_of < closed_time + INTERVAL '720 hours' THEN RETURN FALSE; END IF;

    INSERT INTO public.support_retention_authorizations(transaction_id,backend_pid,conversation_id)
    VALUES (txid_current(),pg_backend_pid(),p_conversation_id);
    DELETE FROM public.support_messages WHERE conversation_id=p_conversation_id;
    UPDATE public.support_conversation_events
       SET actor_user_id=NULL,previous_assignee_user_id_snapshot=NULL,
           new_assignee_user_id_snapshot=NULL,reason=NULL
     WHERE conversation_id=p_conversation_id;
    UPDATE public.support_conversations
       SET owner_user_id=NULL,last_message_at=NULL,user_last_read_at=NULL,staff_last_read_at=NULL,
           content_purged_at=p_as_of,updated_at=clock_timestamp(),version=version+1
     WHERE id=p_conversation_id;
    DELETE FROM public.support_retention_authorizations
     WHERE transaction_id=txid_current() AND backend_pid=pg_backend_pid()
       AND conversation_id=p_conversation_id;
    RETURN TRUE;
END;
$$;

ALTER TABLE public.support_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_conversation_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_retention_authorizations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.support_conversations, public.support_messages, public.support_conversation_events FROM PUBLIC;
REVOKE ALL ON public.support_retention_authorizations FROM PUBLIC;
REVOKE ALL ON FUNCTION public.guard_support_conversation_identity() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.prevent_support_history_mutation() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.purge_expired_support_conversation(UUID,TIMESTAMPTZ) FROM PUBLIC;

DO $runtime_privileges$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        EXECUTE 'REVOKE ALL ON public.support_conversations, public.support_messages, public.support_conversation_events FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        EXECUTE 'REVOKE ALL ON public.support_conversations, public.support_messages, public.support_conversation_events, public.support_retention_authorizations FROM authenticated';
        -- Supabase installs direct per-role default EXECUTE grants for public-schema functions.
        EXECUTE 'REVOKE ALL ON FUNCTION public.purge_expired_support_conversation(UUID,TIMESTAMPTZ) FROM authenticated';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        EXECUTE 'REVOKE ALL ON public.support_retention_authorizations FROM anon';
        -- REVOKE FROM PUBLIC alone does not remove Supabase's direct default-ACL grants.
        EXECUTE 'REVOKE ALL ON FUNCTION public.purge_expired_support_conversation(UUID,TIMESTAMPTZ) FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
        EXECUTE 'REVOKE ALL ON public.support_retention_authorizations FROM service_role';
        EXECUTE 'CREATE POLICY support_conversations_backend_only ON public.support_conversations TO service_role USING (true) WITH CHECK (true)';
        EXECUTE 'CREATE POLICY support_messages_backend_only ON public.support_messages TO service_role USING (true) WITH CHECK (true)';
        EXECUTE 'CREATE POLICY support_events_backend_only ON public.support_conversation_events TO service_role USING (true) WITH CHECK (true)';
        GRANT SELECT, INSERT, UPDATE ON public.support_conversations TO service_role;
        GRANT SELECT, INSERT ON public.support_messages, public.support_conversation_events TO service_role;
        GRANT USAGE, SELECT ON SEQUENCE public.support_messages_id_seq, public.support_conversation_events_id_seq TO service_role;
        GRANT EXECUTE ON FUNCTION public.purge_expired_support_conversation(UUID,TIMESTAMPTZ) TO service_role;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='postgres') THEN
        EXECUTE 'CREATE POLICY support_conversations_postgres_backend ON public.support_conversations TO postgres USING (true) WITH CHECK (true)';
        EXECUTE 'CREATE POLICY support_messages_postgres_backend ON public.support_messages TO postgres USING (true) WITH CHECK (true)';
        EXECUTE 'CREATE POLICY support_events_postgres_backend ON public.support_conversation_events TO postgres USING (true) WITH CHECK (true)';
    END IF;
END
$runtime_privileges$;

DO $postflight$
BEGIN
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.support_conversations'::regclass)
       OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.support_messages'::regclass)
       OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.support_conversation_events'::regclass)
       OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.support_retention_authorizations'::regclass) THEN
        RAISE EXCEPTION 'Postflight: support tables must have RLS enabled.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.support_conversations'::regclass
                   AND tgname='trg_support_conversation_identity' AND tgenabled='O')
       OR NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.support_messages'::regclass
                   AND tgname='trg_support_messages_append_only' AND tgenabled='O')
       OR NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.support_conversation_events'::regclass
                   AND tgname='trg_support_events_append_only' AND tgenabled='O') THEN
        RAISE EXCEPTION 'Postflight: support identity/history triggers are missing or disabled.';
    END IF;
    IF to_regclass('public.idx_support_conversations_owner_updated') IS NULL
       OR to_regclass('public.idx_support_conversations_queue') IS NULL
       OR to_regclass('public.idx_support_conversations_retention') IS NULL
       OR to_regclass('public.uq_support_message_idempotency') IS NULL
       OR to_regclass('public.idx_support_messages_conversation_time') IS NULL
       OR to_regclass('public.idx_support_events_conversation_time') IS NULL THEN
        RAISE EXCEPTION 'Postflight: a required support lookup/idempotency index is missing.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.support_conversations'::regclass
                   AND conname='ck_support_conversation_state' AND convalidated)
       OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.support_messages'::regclass
                   AND conname='ck_support_message_sender' AND convalidated)
       OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.support_conversation_events'::regclass
                   AND conname='ck_support_event_type' AND convalidated) THEN
        RAISE EXCEPTION 'Postflight: a required support state constraint is missing or unvalidated.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') AND (
       NOT has_table_privilege('service_role','public.support_conversations','SELECT,INSERT,UPDATE')
       OR NOT has_table_privilege('service_role','public.support_messages','SELECT,INSERT')
       OR NOT has_table_privilege('service_role','public.support_conversation_events','SELECT,INSERT')
       OR NOT has_sequence_privilege('service_role','public.support_messages_id_seq','USAGE')
       OR NOT has_sequence_privilege('service_role','public.support_conversation_events_id_seq','USAGE')
       OR has_table_privilege('service_role','public.support_retention_authorizations','SELECT,INSERT,UPDATE,DELETE')) THEN
        RAISE EXCEPTION 'Postflight: backend service_role privileges are incomplete.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon')
       AND (has_table_privilege('anon','public.support_messages','SELECT')
            OR has_table_privilege('anon','public.support_retention_authorizations','SELECT')) THEN
        RAISE EXCEPTION 'Postflight: anonymous role must not read support messages.';
    END IF;
    IF to_regprocedure('public.purge_expired_support_conversation(uuid,timestamptz)') IS NULL THEN
        RAISE EXCEPTION 'Postflight: controlled retention function is missing or anonymously executable.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon')
       AND has_function_privilege('anon','public.purge_expired_support_conversation(uuid,timestamptz)','EXECUTE') THEN
        RAISE EXCEPTION 'Postflight: controlled retention function is anonymously executable.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated')
       AND has_function_privilege('authenticated','public.purge_expired_support_conversation(uuid,timestamptz)','EXECUTE') THEN
        RAISE EXCEPTION 'Postflight: controlled retention function is executable by authenticated clients.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role')
       AND NOT has_function_privilege('service_role','public.purge_expired_support_conversation(uuid,timestamptz)','EXECUTE') THEN
        RAISE EXCEPTION 'Postflight: service_role cannot execute the controlled retention function.';
    END IF;
END
$postflight$;
COMMIT;
