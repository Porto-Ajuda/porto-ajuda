-- One-time migration proposal for account password recovery.
-- Apply only after a disposable/local preflight. A second execution fails at
-- CREATE TABLE and rolls back without changing the existing installation.
BEGIN;

CREATE TABLE public.recuperacoes_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NULL UNIQUE,
    email_key VARCHAR(64) NOT NULL,
    ip_key VARCHAR(64) NOT NULL,
    solicitado_em TIMESTAMPTZ NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL,
    consumido_em TIMESTAMPTZ NULL,
    tentativas INTEGER NOT NULL DEFAULT 0 CHECK (tentativas BETWEEN 0 AND 10),
    CONSTRAINT ck_recuperacoes_senha_expiry CHECK (expira_em > solicitado_em),
    CONSTRAINT ck_recuperacoes_senha_token_user CHECK (token_hash IS NULL OR usuario_id IS NOT NULL)
);

CREATE INDEX idx_recuperacoes_senha_user_active
    ON public.recuperacoes_senha (usuario_id, expira_em)
    WHERE consumido_em IS NULL;
CREATE INDEX idx_recuperacoes_senha_email_rate
    ON public.recuperacoes_senha (email_key, solicitado_em);
CREATE INDEX idx_recuperacoes_senha_ip_rate
    ON public.recuperacoes_senha (ip_key, solicitado_em);
CREATE INDEX idx_recuperacoes_senha_requested
    ON public.recuperacoes_senha (solicitado_em);

ALTER TABLE public.recuperacoes_senha ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.recuperacoes_senha FROM PUBLIC;
DO $privileges$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON TABLE public.recuperacoes_senha FROM anon';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE 'REVOKE ALL ON TABLE public.recuperacoes_senha FROM authenticated';
    END IF;
END
$privileges$;

DO $postflight$
DECLARE
    recovery_table regclass := to_regclass('public.recuperacoes_senha');
BEGIN
    IF recovery_table IS NULL
       OR NOT EXISTS (SELECT 1 FROM pg_class WHERE oid = recovery_table AND relrowsecurity)
       OR pg_get_userbyid((SELECT relowner FROM pg_class WHERE oid = recovery_table)) <> current_user
       OR EXISTS (SELECT 1 FROM pg_policy WHERE polrelid = recovery_table)
       OR EXISTS (
           SELECT 1
           FROM pg_class c,
                LATERAL aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) acl
           WHERE c.oid = recovery_table AND acl.grantee = 0
       ) THEN
        RAISE EXCEPTION 'Migração de recuperação abortada: owner, RLS, policies ou ACLs divergentes.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_roles r
        WHERE r.rolname IN ('anon', 'authenticated')
          AND has_table_privilege(r.rolname, recovery_table,
              'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
    ) THEN
        RAISE EXCEPTION 'Migração de recuperação abortada: privilégios diretos para roles REST.';
    END IF;
END
$postflight$;

COMMIT;
