    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles r WHERE r.rolname IN ('anon','authenticated','service_role') AND
       (has_sequence_privilege(r.rolname,'public.moderation_appeals_id_seq','USAGE,SELECT,UPDATE') OR
        has_sequence_privilege(r.rolname,'public.moderation_point_ledger_id_seq','USAGE,SELECT,UPDATE') OR
        has_sequence_privilege(r.rolname,'public.moderation_point_restrictions_id_seq','USAGE,SELECT,UPDATE'))) THEN
        RAISE EXCEPTION 'Postflight: a REST role retains moderation sequence privileges.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
       CROSS JOIN LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
       WHERE n.nspname='public' AND p.proname IN ('guard_moderation_point_ledger','reject_moderation_point_ledger_truncate','guard_moderation_appeal','reject_moderation_appeal_truncate','guard_moderation_appeal_ledger_consistency') AND a.grantee=0)
       OR EXISTS (SELECT 1 FROM pg_roles r JOIN pg_proc p ON p.proname IN
          ('guard_moderation_point_ledger','reject_moderation_point_ledger_truncate','guard_moderation_appeal','reject_moderation_appeal_truncate','guard_moderation_appeal_ledger_consistency')
          JOIN pg_namespace n ON n.oid=p.pronamespace WHERE r.rolname IN ('anon','authenticated','service_role')
          AND n.nspname='public' AND has_function_privilege(r.rolname,p.oid,'EXECUTE')) THEN
        RAISE EXCEPTION 'Postflight: a REST role or PUBLIC retains moderation trigger-function execution.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
       WHERE n.nspname='public' AND p.proname IN ('guard_moderation_point_ledger','reject_moderation_point_ledger_truncate','guard_moderation_appeal','reject_moderation_appeal_truncate','guard_moderation_appeal_ledger_consistency')
         AND (pg_get_userbyid(p.proowner)<>current_user OR NOT has_function_privilege(current_user,p.oid,'EXECUTE'))) THEN
        RAISE EXCEPTION 'Postflight: trigger-function ownership or backend execution privilege is invalid.';
    END IF;
END
$postflight$;
COMMIT;
