CREATE FUNCTION public.guard_moderation_point_ledger() RETURNS trigger
LANGUAGE plpgsql AS $function$
DECLARE decision_target_type TEXT; decision_target_id INTEGER; decision_name TEXT; current_score BIGINT;
DECLARE appeal_user INTEGER; appeal_osc INTEGER; appeal_decision BIGINT; original_points INTEGER;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Moderation point ledger is append-only.';
    END IF;
    IF NEW.subject_user_id IS NOT NULL THEN
        PERFORM 1 FROM public.usuarios WHERE id=NEW.subject_user_id FOR UPDATE;
        IF NOT FOUND AND NEW.origin<>'APPEAL_CORRECTION' THEN
            RAISE EXCEPTION 'A new point decision must reference an existing user.';
        END IF;
        SELECT coalesce(sum(points_delta),0)::bigint INTO current_score FROM public.moderation_point_ledger WHERE subject_user_id=NEW.subject_user_id;
    ELSE
        PERFORM 1 FROM public.oscs WHERE id=NEW.subject_osc_id FOR UPDATE;
        SELECT coalesce(sum(points_delta),0)::bigint INTO current_score FROM public.moderation_point_ledger WHERE subject_osc_id=NEW.subject_osc_id;
    END IF;
    IF current_score+NEW.points_delta<0 THEN RAISE EXCEPTION 'Moderation point balance cannot be negative.'; END IF;
    IF NEW.origin='UPHELD_DECISION' THEN
        SELECT target_type,target_id,decision INTO decision_target_type,decision_target_id,decision_name
          FROM public.content_report_review_history WHERE id=NEW.decision_history_id;
        IF decision_name IS DISTINCT FROM 'UPHOLD'
           OR (decision_target_type='OSC' AND NEW.subject_osc_id IS DISTINCT FROM decision_target_id)
           OR (decision_target_type='POST' AND NOT EXISTS
                (SELECT 1 FROM public.post p WHERE p.id=decision_target_id AND p.id_usuario=NEW.subject_user_id)) THEN
            RAISE EXCEPTION 'Point subject does not match the upheld decision target.';
        END IF;
    ELSIF NEW.origin='APPEAL_CORRECTION' THEN
        SELECT subject_user_id,subject_osc_id,decision_history_id INTO appeal_user,appeal_osc,appeal_decision
          FROM public.moderation_appeals WHERE id=NEW.appeal_id FOR UPDATE;
        IF appeal_user IS DISTINCT FROM NEW.subject_user_id OR appeal_osc IS DISTINCT FROM NEW.subject_osc_id
           OR appeal_decision IS DISTINCT FROM NEW.decision_history_id THEN
            RAISE EXCEPTION 'Appeal correction subject mismatch.';
        END IF;
        SELECT coalesce(sum(points_delta),0) INTO original_points FROM public.moderation_point_ledger
         WHERE decision_history_id=NEW.decision_history_id AND origin IN ('UPHELD_DECISION','APPEAL_CORRECTION');
        IF NEW.points_delta >= 0 OR -NEW.points_delta > original_points THEN
            RAISE EXCEPTION 'Appeal correction exceeds unreversed points.';
        END IF;
    END IF;
    RETURN NEW;
END
$function$;
CREATE TRIGGER trg_moderation_point_ledger_immutable
    BEFORE INSERT OR UPDATE OR DELETE ON public.moderation_point_ledger
    FOR EACH ROW EXECUTE FUNCTION public.guard_moderation_point_ledger();
