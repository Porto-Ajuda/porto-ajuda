CREATE FUNCTION public.guard_moderation_appeal() RETURNS trigger
LANGUAGE plpgsql AS $function$
DECLARE decision_name TEXT; decision_type TEXT; decision_target INTEGER; original_points INTEGER;
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.status<>'PENDING' OR NEW.reviewed_at IS NOT NULL THEN
            RAISE EXCEPTION 'An appeal must be submitted as pending.';
        END IF;
        SELECT decision,target_type,target_id INTO decision_name,decision_type,decision_target
          FROM public.content_report_review_history WHERE id=NEW.decision_history_id;
        IF decision_name IS DISTINCT FROM 'UPHOLD'
           OR (decision_type='OSC' AND (NEW.subject_osc_id IS DISTINCT FROM decision_target OR NOT EXISTS
             (SELECT 1 FROM public.moderation_point_ledger l WHERE l.decision_history_id=NEW.decision_history_id
                AND l.origin='UPHELD_DECISION' AND l.subject_osc_id=NEW.subject_osc_id)))
           OR (decision_type='POST' AND NOT EXISTS
             (SELECT 1 FROM public.moderation_point_ledger l WHERE l.decision_history_id=NEW.decision_history_id
                AND l.origin='UPHELD_DECISION' AND l.subject_user_id=NEW.subject_user_id)) THEN
            RAISE EXCEPTION 'Appeal does not match a point-bearing upheld decision.';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM public.usuarios WHERE id=NEW.appellant_user_id) THEN
            RAISE EXCEPTION 'An appeal must be submitted by an existing account.';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' OR OLD.decision_history_id IS DISTINCT FROM NEW.decision_history_id
       OR OLD.subject_user_id IS DISTINCT FROM NEW.subject_user_id OR OLD.subject_osc_id IS DISTINCT FROM NEW.subject_osc_id
       OR OLD.appellant_user_id IS DISTINCT FROM NEW.appellant_user_id OR OLD.justification IS DISTINCT FROM NEW.justification
       OR OLD.created_at IS DISTINCT FROM NEW.created_at OR OLD.status<>'PENDING'
       OR NEW.status NOT IN ('REJECTED','PARTIAL','ACCEPTED') THEN
        RAISE EXCEPTION 'Appeal identity/history is immutable and can be reviewed only once.';
    END IF;
    SELECT coalesce(sum(points_delta),0)::integer INTO original_points FROM public.moderation_point_ledger
     WHERE decision_history_id=NEW.decision_history_id AND origin='UPHELD_DECISION';
    IF (NEW.status='REJECTED' AND NEW.points_reversed<>0)
       OR (NEW.status='ACCEPTED' AND NEW.points_reversed<>original_points)
       OR (NEW.status='PARTIAL' AND NOT (NEW.points_reversed BETWEEN 1 AND original_points-1)) THEN
        RAISE EXCEPTION 'Appeal decision and point reversal amount are inconsistent.';
    END IF;
    RETURN NEW;
END
$function$;
CREATE TRIGGER trg_moderation_appeal_guard BEFORE INSERT OR UPDATE OR DELETE ON public.moderation_appeals
    FOR EACH ROW EXECUTE FUNCTION public.guard_moderation_appeal();

-- The service inserts a compensating ledger row before changing the appeal from PENDING
-- to ACCEPTED/PARTIAL. Validate the final pair at commit so either statement order within
-- the same transaction remains atomic, while a partial write can never be committed.
CREATE FUNCTION public.guard_moderation_appeal_ledger_consistency() RETURNS trigger
LANGUAGE plpgsql AS $function$
DECLARE affected_appeal_id BIGINT; appeal_row public.moderation_appeals%ROWTYPE;
DECLARE movement_count INTEGER; movement_delta INTEGER; movement_user INTEGER; movement_osc INTEGER;
DECLARE movement_decision BIGINT;
BEGIN
    IF TG_TABLE_NAME='moderation_appeals' THEN
        affected_appeal_id := COALESCE(NEW.id,OLD.id);
    ELSE
        affected_appeal_id := COALESCE(NEW.appeal_id,OLD.appeal_id);
    END IF;
    IF affected_appeal_id IS NULL THEN RETURN NULL; END IF;

    SELECT * INTO appeal_row FROM public.moderation_appeals WHERE id=affected_appeal_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Appeal consistency check could not find the referenced appeal.';
    END IF;

    SELECT count(*)::integer, min(points_delta), min(subject_user_id), min(subject_osc_id), min(decision_history_id)
      INTO movement_count,movement_delta,movement_user,movement_osc,movement_decision
      FROM public.moderation_point_ledger
     WHERE appeal_id=affected_appeal_id AND origin='APPEAL_CORRECTION';

    IF appeal_row.status IN ('ACCEPTED','PARTIAL') THEN
        IF movement_count<>1 OR movement_delta<>-appeal_row.points_reversed
           OR movement_user IS DISTINCT FROM appeal_row.subject_user_id
           OR movement_osc IS DISTINCT FROM appeal_row.subject_osc_id
           OR movement_decision IS DISTINCT FROM appeal_row.decision_history_id THEN
            RAISE EXCEPTION 'Successful appeal must have exactly one matching compensating ledger movement.';
        END IF;
    ELSIF movement_count<>0 THEN
        RAISE EXCEPTION 'Pending or rejected appeal cannot have a compensating ledger movement.';
    END IF;
    RETURN NULL;
END
$function$;
CREATE CONSTRAINT TRIGGER trg_moderation_appeal_ledger_consistency
    AFTER INSERT OR UPDATE ON public.moderation_appeals
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
    EXECUTE FUNCTION public.guard_moderation_appeal_ledger_consistency();
CREATE CONSTRAINT TRIGGER trg_moderation_ledger_appeal_consistency
    AFTER INSERT ON public.moderation_point_ledger
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
    EXECUTE FUNCTION public.guard_moderation_appeal_ledger_consistency();

