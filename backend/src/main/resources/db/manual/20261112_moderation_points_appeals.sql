-- Porto Ajuda moderation points, point-derived restrictions, and appeals.
-- One-shot migration. Requires 20261111_content_reporting_moderation.sql already applied.
-- No historical report decisions are backfilled into the points ledger.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';

DO $preflight$
BEGIN
    -- Supabase's project-scoped postgres login is commonly exposed as postgres.<project-ref>.
    -- Accept that owner role only with BYPASSRLS, non-superuser status, and explicit public-schema DDL rights.
    IF (current_user <> 'postgres' AND current_user !~ '^postgres\.[a-z0-9]+$')
       OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname=current_user AND rolbypassrls AND NOT rolsuper)
       OR NOT has_schema_privilege(current_user,'public','USAGE')
       OR NOT has_schema_privilege(current_user,'public','CREATE') THEN
        RAISE EXCEPTION 'Preflight: execute as postgres or its project-scoped BYPASSRLS non-superuser owner role with public-schema DDL rights.';
    END IF;
    IF to_regclass('public.usuarios') IS NULL OR to_regclass('public.oscs') IS NULL
       OR to_regclass('public.post') IS NULL OR to_regclass('public.content_reports') IS NULL
       OR to_regclass('public.content_moderation_blocks') IS NULL
       OR to_regclass('public.content_report_review_history') IS NULL THEN
        RAISE EXCEPTION 'Preflight: base and reporting migration objects are required.';
    END IF;
    IF to_regclass('public.moderation_point_ledger') IS NOT NULL
       OR to_regclass('public.moderation_point_restrictions') IS NOT NULL
       OR to_regclass('public.moderation_appeals') IS NOT NULL
       OR to_regprocedure('public.guard_moderation_point_ledger()') IS NOT NULL
       OR to_regprocedure('public.guard_moderation_appeal()') IS NOT NULL
       OR to_regprocedure('public.guard_moderation_appeal_ledger_consistency()') IS NOT NULL
       OR EXISTS (SELECT 1 FROM pg_trigger WHERE NOT tgisinternal AND tgname IN
          ('trg_moderation_point_ledger_immutable','trg_moderation_point_ledger_no_truncate',
           'trg_moderation_appeal_guard','trg_moderation_appeals_no_truncate',
           'trg_moderation_appeal_ledger_consistency','trg_moderation_ledger_appeal_consistency')) THEN
        RAISE EXCEPTION 'Preflight: moderation point/appeal objects already exist; inspect instead of rerunning.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('anon','authenticated','service_role')
               AND has_table_privilege(rolname,'public.content_report_review_history','SELECT')) THEN
        RAISE EXCEPTION 'Preflight: REST roles unexpectedly have direct reporting-history access.';
    END IF;
END
$preflight$;

CREATE TABLE public.moderation_appeals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_history_id BIGINT NOT NULL UNIQUE
        REFERENCES public.content_report_review_history(id) ON DELETE RESTRICT,
    -- Historical numeric identity is intentionally retained without an FK so the existing
    -- six-month account-erasure lifecycle is not blocked by an append-only appeal record.
    subject_user_id INTEGER,
    subject_osc_id INTEGER REFERENCES public.oscs(id) ON DELETE RESTRICT,
    appellant_user_id INTEGER NOT NULL,
    justification VARCHAR(2000) NOT NULL CHECK (length(btrim(justification)) BETWEEN 1 AND 2000),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','REJECTED','PARTIAL','ACCEPTED')),
    decision_justification VARCHAR(2000),
    points_reversed INTEGER NOT NULL DEFAULT 0 CHECK (points_reversed BETWEEN 0 AND 3),
    reviewed_by_user_id_snapshot INTEGER,
    reviewer_profile_snapshot VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT ck_moderation_appeal_subject CHECK
      ((subject_user_id IS NOT NULL AND subject_osc_id IS NULL) OR
       (subject_user_id IS NULL AND subject_osc_id IS NOT NULL)),
    CONSTRAINT ck_moderation_appeal_identity CHECK
      ((subject_user_id IS NULL OR subject_user_id>0) AND (subject_osc_id IS NULL OR subject_osc_id>0) AND appellant_user_id>0),
    CONSTRAINT ck_moderation_appeal_review CHECK
      ((status='PENDING' AND reviewed_at IS NULL AND decision_justification IS NULL
        AND reviewed_by_user_id_snapshot IS NULL AND reviewer_profile_snapshot IS NULL
        AND points_reversed=0)
       OR (status<>'PENDING' AND reviewed_at IS NOT NULL
        AND created_at<=reviewed_at
        AND decision_justification IS NOT NULL AND length(btrim(decision_justification)) BETWEEN 1 AND 2000
        AND reviewed_by_user_id_snapshot IS NOT NULL AND reviewed_by_user_id_snapshot>0
        AND reviewer_profile_snapshot IN ('SUPER_ADMIN','PLATFORM_ADMIN')))
);
CREATE INDEX idx_moderation_appeals_queue ON public.moderation_appeals(status,created_at,id);
CREATE INDEX idx_moderation_appeals_subject_user ON public.moderation_appeals(subject_user_id,created_at DESC,id DESC);
CREATE INDEX idx_moderation_appeals_subject_osc ON public.moderation_appeals(subject_osc_id,created_at DESC,id DESC);

CREATE TABLE public.moderation_point_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_user_id INTEGER,
    subject_osc_id INTEGER REFERENCES public.oscs(id) ON DELETE RESTRICT,
    points_delta INTEGER NOT NULL CHECK (points_delta BETWEEN -10 AND 10 AND points_delta<>0),
    origin VARCHAR(32) NOT NULL CHECK (origin IN ('UPHELD_DECISION','MANUAL_ADJUSTMENT','APPEAL_CORRECTION')),
    decision_history_id BIGINT REFERENCES public.content_report_review_history(id) ON DELETE RESTRICT,
    appeal_id BIGINT REFERENCES public.moderation_appeals(id) ON DELETE RESTRICT,
    reference_key UUID NOT NULL UNIQUE,
    actor_user_id_snapshot INTEGER NOT NULL,
    actor_profile_snapshot VARCHAR(32) NOT NULL,
    justification VARCHAR(2000) NOT NULL CHECK (length(btrim(justification)) BETWEEN 1 AND 2000),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_moderation_points_subject CHECK
      ((subject_user_id IS NOT NULL AND subject_osc_id IS NULL) OR
       (subject_user_id IS NULL AND subject_osc_id IS NOT NULL)),
    CONSTRAINT ck_moderation_points_actor CHECK
      ((subject_user_id IS NULL OR subject_user_id>0) AND (subject_osc_id IS NULL OR subject_osc_id>0)
       AND actor_user_id_snapshot>0),
    CONSTRAINT ck_moderation_points_origin CHECK
      ((origin='UPHELD_DECISION' AND points_delta BETWEEN 1 AND 3 AND decision_history_id IS NOT NULL AND appeal_id IS NULL)
       OR (origin='MANUAL_ADJUSTMENT' AND decision_history_id IS NULL AND appeal_id IS NULL)
       OR (origin='APPEAL_CORRECTION' AND points_delta BETWEEN -3 AND -1 AND decision_history_id IS NOT NULL AND appeal_id IS NOT NULL))
);
